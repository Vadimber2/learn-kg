"use strict";
/* Тест разметки грамматических таблиц собранной страницы (проверка без DOM, по исходнику). */
const fs = require("fs");
const path = require("path");
const assert = require("assert");

const html = require("../server/appshell").buildAppHtml();

// М2, «Аффиксы принадлежности»: столбец «Лицо» — местоимения в илик (менин, сенин…),
// потому что аффикс принадлежности сочетается именно с илик-формой, а не с атооч (мен, сен…).
const from = html.indexOf('L("Аффиксы принадлежности","Possessive affixes"');
const to = html.indexOf("Чередование на стыке", from); // конец ищем после начала карточки, не с начала файла
assert.ok(from > 0 && to > from, "карточка «Аффиксы принадлежности» найдена");
const seg = html.slice(from, to);

// Проверяем свойство, а не фиксированный список: каждая строка — местоимение в илик,
// и ни одной формы атооч (мен, сен, сиз, ал, биз, силер) не осталось. Тогда добавление
// строк «сиздердин», «алардын» тест не сломает, а откат к атооч — сломает.
const ILIK = { мен: "менин", сен: "сенин", сиз: "сиздин", ал: "анын", биз: "биздин",
  силер: "силердин", сиздер: "сиздердин", алар: "алардын" };
const persons = [...seg.matchAll(/h\("tr",\{\},h\("td",\{\},"([^"]+)"\)/g)].map((m) => m[1]);
assert.ok(persons.length >= 6, "строк в таблице: " + persons.length);
const ilik = new Set(Object.values(ILIK));
for (const p of persons) {
  assert.ok(!ILIK[p], "форма атооч «" + p + "» — нужна форма илик «" + ILIK[p] + "»");
  assert.ok(ilik.has(p), "неизвестная форма в столбце «Лицо»: " + p);
}
for (const need of ["менин", "сенин", "сиздин", "анын", "биздин", "силердин", "сиздердин", "алардын"])
  assert.ok(persons.includes(need), "в таблице нет строки «" + need + "»");

// «алар» своего аффикса не имеет — берёт 3-е лицо, как «ал»: строки должны совпадать
const rows = [...seg.matchAll(/h\("tr",\{\},h\("td",\{\},"([^"]+)"\),h\("td",\{\},"([^"]+)"\),h\("td",\{\},"([^"]+)"\)/g)]
  .map((m) => ({ who: m[1], vowel: m[2], cons: m[3] }));
const al = rows.find((r) => r.who === "анын"), alar = rows.find((r) => r.who === "алардын");
assert.ok(al && alar, "строки «анын» и «алардын» найдены");
assert.strictEqual(alar.vowel, al.vowel, "«алардын» берёт тот же аффикс после гласной, что «анын»");
assert.strictEqual(alar.cons, al.cons, "«алардын» берёт тот же аффикс после согласной, что «анын»");

// широкий гласный -ңар/-ыңар: исключение «после о → о, после у → а» должно быть оговорено,
// иначе две колонки строки «силердин» противоречат друг другу
const siler = rows.find((r) => r.who === "силердин");
assert.ok(siler.cons.includes("-уңор") && siler.cons.includes("-уңар"),
  "в строке «силердин» разведены о- и у-варианты: " + siler.cons);
assert.ok(/колуңор/.test(seg) && /жумушуңар/.test(seg), "исключение о/у разобрано примерами");

console.log("grammar-markup.test.js: OK (лицо:", persons.join(", ") + ")");
