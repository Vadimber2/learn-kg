/* Алфавит дорожки: любой буквенный знак вне него читается моделью фонетикой языка
   дорожки. Турецкий алфавит — со своими буквами, английский — только ASCII (потому
   «schön» и «über» в en запрещены наравне с кириллицей). */
const ALPHABET = {
  ru: /[\p{Script=Cyrillic}]/u,
  en: /[A-Za-z]/,
  tr: /[A-Za-zçğıöşüâîûÇĞİÖŞÜÂÎÛ]/,
};
/* Чужой язык как ориентир: имя языка или его диакритики в тексте дорожки.
   Свой язык (и кыргызский, о котором урок) не в списке — на них опираться нужно.
   İngilizce в турецкой дорожке разрешён осознанно: он там не источник звука, а
   контраст («в отличие от английского, гласные не глотаются»). */
const FOREIGN_REF = {
  ru: /немецк|французск|турецк|арабск|испанск|умляут/i,
  en: /\b(French|German|Arabic|Spanish|Turkish|Russian|umlaut)\b/i,
  tr: /\b(Fransızca|Almanca|Arapça|İspanyolca|Rusça|Rus)\b/u,
};

// нормализация — общая с tests/lessons.test.js (правила «дословно из скрипта» не расходятся)
const { norm } = require("./helpers/lesson-script");

function courseVocab() {
  const html = require("../server/appshell").buildAppHtml();
  const m = html.match(/\/\* ===DATA=== \*\/([\s\S]*?)\/\* ===\/DATA=== \*\//);
  assert.ok(m, "маркеры ===DATA=== найдены");
  const sb = { console };
  vm.createContext(sb);
  vm.runInContext(m[1] + "; this.CONTENT=CONTENT;", sb);
  const phrases = new Set(), words = new Set();
  for (const c of Object.values(sb.CONTENT)) {
    for (const v of (c.vocab || [])) {
      if (v.ref || !v.ky) continue;
      phrases.add(norm(v.ky));
      for (const w of norm(v.ky).split(" ")) if (w) words.add(w);
    }
  }
  return { phrases, words };
}

const REG = JSON.parse(fs.readFileSync(VOICES, "utf8"));
const { phrases, words } = courseVocab();

const ids = new Set();          // id тем глобально уникальны: общий бакет аудио m0
const unknown = [];
let checked = 0, tracksTotal = 0, segsTotal = 0;

for (const [mod, file] of Object.entries(LESSON_SCRIPTS)) {
  const S = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "deploy", file), "utf8"));

  /* ── контракт генерации ─────────────────────────────────────────────────── */
  assert.ok(/^\d{4}-\d{2}-\d{2}$/.test(S.updated || ""), mod + ": updated не дата");
  assert.ok(REG.voices[S.voiceRole], mod + ": голос " + S.voiceRole + " отсутствует в voices.json");
  assert.ok(Array.isArray(S.tracks) && S.tracks.length, mod + ": нет треков");
  // мета урока: реестр LESSONS собирается из скрипта, без неё урок безымянный
  assert.strictEqual(S.lesson && S.lesson.mod, mod, mod + ": lesson.mod обязан совпадать с ключом реестра");
  assert.ok(/^[a-z0-9-]{3,24}$/.test(S.lesson.id || ""), mod + ": lesson.id не валиден");
  for (const l of LANGS) {
    assert.ok(S.lesson.title && S.lesson.title[l] && S.lesson.title[l].length > 4, mod + ": нет заголовка урока на " + l);
    assert.ok(S.lesson.intro && S.lesson.intro[l] && S.lesson.intro[l].length > 10, mod + ": нет вступления урока на " + l);
  }
  for (const t of S.tracks) {
    tracksTotal++;
    assert.ok(/^[a-z0-9]{1,12}$/.test(t.id || ""), "id трека не валиден: " + t.id);
    assert.ok(!ids.has(t.id), "id трека дважды (бакет аудио общий): " + t.id);
    ids.add(t.id);
    // заголовок темы — на всех трёх языках (урок целиком трёхъязычный)
    for (const l of LANGS) assert.ok(t.title && t.title[l] && t.title[l].length > 4,
      t.id + ": нет заголовка на " + l);
    assert.ok(Array.isArray(t.segments) && t.segments.length >= 2, t.id + ": нужно ≥2 сегментов");
    for (const [i, seg] of t.segments.entries()) {
      segsTotal++;
      const at = t.id + "/" + (i + 1) + ": ";
      assert.ok(["explain", "example"].includes(seg.kind), at + "kind только explain или example");
      if (seg.kind === "explain") {
        for (const l of LANGS) {
          assert.ok(seg.text && seg.text[l] && seg.text[l].trim().length > 2, at + "нет текста на " + l);
          // серверная ручка режет текст до 500 знаков
          assert.ok(seg.text[l].length <= 480, at + l + ": длина " + seg.text[l].length + " > 480");
          // кыргызские буквы в объяснении = модель прочтёт их фонетикой этого языка
          // флаг i обязателен: без него заглавные Ң/Ө/Ү проходили гейт насквозь
          // (нашёл валидатор скилла на подставном тексте «Ө неверная буква»)
          assert.ok(!/[ңөү]/i.test(seg.text[l]), at + l + ": кыргызские буквы в объяснении — вынеси в example");
          // Правило ориентира: пример-ориентир берётся ИЗ ЯЗЫКА ДОРОЖКИ. Буква чужого
          // алфавита читается фонетикой своего языка (кириллица в en/tr → тарабарщина),
          // а слово чужого языка ученик не знает и прочесть не может.
          const alien = [...seg.text[l]].filter((ch) => /\p{L}/u.test(ch) && !ALPHABET[l].test(ch));
          assert.deepStrictEqual(alien, [], at + l + ": буквы чужого алфавита " + JSON.stringify(alien) +
            " — опиши звук средствами языка дорожки, показ звука оставь кыргызскому голосу");
          // Ориентир из третьего языка бесполезен («откуда русскому знать немецкий
          // умляут») и читается неверно: «song» английским словом в русской дорожке
          // прозвучало с «г», которого в носовом нет. Названия чужих языков и чужих
          // диакритик — запрещены; свой язык и кыргызский — можно.
          assert.ok(!FOREIGN_REF[l].test(seg.text[l]),
            at + l + ": ориентир из чужого языка (" + (seg.text[l].match(FOREIGN_REF[l]) || [])[0] +
            ") — объясняй через то, что слушатель этого языка уже умеет");
        }
        // Носовой нельзя показывать написанным словом: у диктора вылезает «г» на конце
        // (услышано и в русской, и в английской дорожке). Показывает кыргызский голос.
        assert.ok(!/\b(sing|song|singing)\b/i.test(seg.text.en),
          at + "en: носовой через написанное слово — диктор произносит «г»; оставь показ примеру");
        assert.ok(seg.say == null, at + "say допустим только у кыргызских примеров");
      } else {
        assert.ok(seg.ky && seg.ky.trim(), at + "пример без кыргызского текста");
        for (const l of LANGS) assert.ok(seg.gloss && seg.gloss[l], at + "нет глосса на " + l);
        // say — орфоэпическая запись только для TTS-запроса; на экран идёт ky.
        // Кириллица и та же пунктуация: латиница/IPA голым текстом v3 читает как тарабарщину.
        if (seg.say != null) {
          assert.ok(/^[А-Яа-яЁёӨөҮүҢң .,!?—-]+$/.test(seg.say) && seg.say.length <= 300,
            at + "say — только кириллическая орфоэпия: " + seg.say);
          assert.notStrictEqual(seg.say, seg.ky, at + "say совпадает с ky — лишняя запись");
        }
      }
    }
    assert.ok(t.segments.some((s) => s.kind === "explain"), t.id + ": нет объяснения");
    assert.ok(t.segments.some((s) => s.kind === "example"), t.id + ": нет кыргызских примеров");
    // звук показывается и словами, и внутри фразы
    assert.ok(t.segments.filter((s) => s.kind === "example").some((s) => norm(s.ky).split(" ").length >= 3),
      t.id + ": нет примера-фразы (только отдельные слова)");
    // небольшая пауза в конце темы: слушатель успевает переключиться
    assert.ok(t.segments[t.segments.length - 1].gap === true, t.id + ": в конце темы нет паузы (gap)");
    /* Цитаты-пруфы (требование владельца): каждое объяснение опирается на источник,
       и источник сохранён В ДАННЫХ рядом с текстом, а не в голове автора. Формат:
       refs: [{claim, src, quote?}] — quote обязательна хотя бы у одного ref трека,
       кроме явно эмпирических/методических (src описывает проверку). */
    assert.ok(Array.isArray(t.refs) && t.refs.length >= 1, t.id + ": нет ни одной цитаты-пруфа (refs)");
    for (const r of t.refs) {
      assert.ok(r.claim && r.claim.length >= 15, t.id + ": ref без внятного утверждения");
      assert.ok(r.src && r.src.length >= 10, t.id + ": ref без источника");
      if (r.quote != null) assert.ok(r.quote.length >= 15, t.id + ": цитата подозрительно коротка");
    }
    assert.ok(t.refs.some((r) => r.quote) || t.refs.every((r) => /эмпирика|tests\//.test(r.src)),
      t.id + ": ни одной дословной цитаты — либо приведи цитату, либо источник-проверка");
  }

  /* ── главное: ни одной сочинённой кыргызской фразы ──────────────────────── */
  for (const t of S.tracks) {
    for (const seg of t.segments.filter((s) => s.kind === "example")) {
      // высказывания внутри сегмента: «Көл. Көз. Өз.» → три независимые проверки
      for (const raw of seg.ky.split(/[.!?,;]+/)) {
        const u = norm(raw);
        if (!u) continue;
        checked++;
        if (phrases.has(u)) continue;                       // дословная фраза курса
        if (!u.includes(" ") && words.has(u)) continue;      // слово курса
        if (LESSON_DEMOS[u]) continue;                       // обоснованный пример источника
        unknown.push({ lesson: mod, track: t.id, text: u });
      }
    }
  }
}

assert.deepStrictEqual(unknown, [],
  "кыргызские высказывания вне курса и вне белого списка (сочинены?): " +
  JSON.stringify(unknown, null, 2) +
  "\nЛибо возьми фразу из курса дословно, либо добавь запись в LESSON_DEMOS с обоснованием.");

// белый список не должен разрастаться незаметно: каждая запись обязана иметь обоснование
for (const [k, why] of Object.entries(LESSON_DEMOS))
  assert.ok(why && why.length > 10, "LESSON_DEMOS[" + k + "]: обоснование обязательно");

console.log("pronunciation.test.js: OK (уроков: " + Object.keys(LESSON_SCRIPTS).length + ", " +
  tracksTotal + " треков, " + segsTotal + " сегментов, " + checked +
  " кыргызских высказываний сверены с курсом и источниками)");
