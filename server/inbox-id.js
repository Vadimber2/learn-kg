/* Чат с преподавателем: форма идентификатора треда — ОДИН источник для подписи куки
   (server/inbox-auth.js) и для имени файла (server/inbox-store.js). Две копии регекспа
   разъехались бы, и одна сторона принимала бы id, который другая считает чужим.
   v-<24 hex> — гость, u-<логин> — ученик. */
const CHAT_ID_RE = /^(v-[0-9a-f]{24}|u-[a-zA-Z0-9_.-]{2,32})$/;

module.exports = { CHAT_ID_RE };
