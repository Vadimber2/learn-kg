#!/usr/bin/env node
"use strict";
/* Роутер скиллов (hook UserPromptSubmit).
   Зачем: выбор скилла моделью стохастичен — замер 21.08.2026 дал 6/9/6/7/6 из 10 на
   одном наборе и неизменных описаниях, причём промах всегда «ни один скилл», а не
   «сработал чужой». Значит проблема не в разграничении описаний, а в самой готовности
   потянуться к скиллу; лечится это не текстом описания, а детерминированным правилом.
   Хук печатает одну строку-указатель — она попадает в контекст запроса, и знание
   проекта (реестры, гейты, грабли) не теряется из-за случайности.
   Правила — данные: новая тема = запись в ROUTES, ноль правок логики. */

// Порядок значим: первое совпадение выигрывает. Уроки идут раньше озвучки, потому что
// «озвучь урок» — работа по конвейеру уроков (у них свой генератор и свои гейты),
// а не обычная перегенерация карточек.
const ROUTES = [
  { skill: "kyrgyz-lessons", what: "аудиоуроки learn.kg: скрипт с citation, слайды, озвучка урока, видео",
    re: /аудиоурок|видеоурок|шортс|слайд|в уроке|урок (?:модул|m\d|№\s*\d|\d)|урока? (?:m\d|модул)/i },
  { skill: "kyrgyz-listening", what: "раздел «Аудирование» (STT): блоки, дриллы, лимиты, учёт затрат",
    re: /аудирован|распознаван|\bstt\b|scribe|дрилл(?:е|ы|ов)? (?:звук|соглас|гласн|окончан)|слушай-повтори/i },
  { skill: "kyrgyz-tts", what: "озвучка через ElevenLabs: реестр голосов, режимы стабильности, обрывы хвоста",
    re: /озвуч|перегенер|диктор|голос|произнош|elevenlabs|стабильност|обрыв|проглотил|звучит не так/i },
  { skill: "kyrgyz-course", what: "курсы и модули: реестры CONTENT/COURSES/MODULE_META, чеклисты нового модуля и курса",
    re: /новый модуль|модуль в курс|добавлени(?:е|я) модул|уровень (?:a2|b1|b2|c1|c2)|курс (?:a2|b1|b2|c1|c2)|COURSES|CONTENT_READY|MODULE_META/i },
  { skill: "kyrgyz-a1", what: "устройство тренажёра learn.kg: части app/src, сборка, персональные варианты",
    re: /appshell|manifest\.json|app\/src|персональн(?:ый|ого) вариант|маркер-блок/i },
];

function routeFor(prompt) {
  const s = String(prompt || "");
  for (const r of ROUTES) if (r.re.test(s)) return r;
  return null;
}

/* Формулировка императивна намеренно: мягкое «стоит заглянуть» модель регулярно
   игнорировала — во втором замере темы курсов дважды прошли без вызова Skill.
   Требование «первым действием, до любого ответа» промахов не оставило. */
function hintFor(r) {
  return "ОБЯЗАТЕЛЬНО: первым действием вызови Skill(" + r.skill + ") — это тема скилла `" +
    r.skill + "` (" + r.what + "). Не отвечай и не начинай работу, не загрузив его: " +
    "в нём реестры, гейты и уже оплаченные ошибками грабли проекта, без них ответ " +
    "разойдётся с каноном learn.kg.";
}

module.exports = { ROUTES, routeFor, hintFor };

if (require.main === module) {
  let raw = "";
  process.stdin.setEncoding("utf8");
  process.stdin.on("data", (c) => { raw += c; });
  process.stdin.on("end", () => {
    let ev = {};
    try { ev = JSON.parse(raw || "{}"); } catch (e) { process.exit(0); }
    const r = routeFor(ev.prompt);
    // диагностика замеров: KGA1_HOOK_LOG=<файл> пишет строку на каждый вызов —
    // так видно, сработал ли хук вообще (промах модели и неработающий хук выглядят
    // на замере одинаково, а лечатся по-разному)
    if (process.env.KGA1_HOOK_LOG) {
      try { require("fs").appendFileSync(process.env.KGA1_HOOK_LOG,
        (r ? r.skill : "-") + "\t" + String(ev.prompt || "").slice(0, 40) + "\n"); } catch (e) {}
    }
    // молчание — норма: запрос вне тем проекта не должен получать никакой строки
    if (r) process.stdout.write(hintFor(r) + "\n");
    process.exit(0);
  });
}
